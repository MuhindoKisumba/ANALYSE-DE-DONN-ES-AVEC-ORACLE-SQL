-- 1. CRÉATION D'UNE TABLE D'EXEMPLE
---------------------------------------------------------------------------------------------------

CREATE TABLE VENTES
(
    ID_VENTE       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DATE_VENTE     DATE,
    PROVINCE       VARCHAR2(100),
    VILLE          VARCHAR2(100),
    PRODUIT        VARCHAR2(100),
    CATEGORIE      VARCHAR2(100),
    QUANTITE       NUMBER,
    PRIX_UNITAIRE  NUMBER(12,2),
    MONTANT_TOTAL  NUMBER(12,2)
);

