---------------------------------------------------------------------------------------------------
-- 3. VISUALISATION DES DONNÉES
---------------------------------------------------------------------------------------------------

SELECT *
FROM VENTES;

---------------------------------------------------------------------------------------------------
-- 4. NOMBRE TOTAL D'ENREGISTREMENTS
---------------------------------------------------------------------------------------------------

SELECT COUNT(*) AS TOTAL_ENREGISTREMENTS
FROM VENTES;

---------------------------------------------------------------------------------------------------
-- 5. SOMME DES VENTES
---------------------------------------------------------------------------------------------------

SELECT SUM(MONTANT_TOTAL) AS CHIFFRE_AFFAIRES
FROM VENTES;

---------------------------------------------------------------------------------------------------
-- 6. MOYENNE DES VENTES
---------------------------------------------------------------------------------------------------

SELECT AVG(MONTANT_TOTAL) AS MOYENNE_VENTE
FROM VENTES;

---------------------------------------------------------------------------------------------------
-- 7. VENTE MINIMUM ET MAXIMUM
---------------------------------------------------------------------------------------------------

SELECT
    MIN(MONTANT_TOTAL) AS VENTE_MIN,
    MAX(MONTANT_TOTAL) AS VENTE_MAX
FROM VENTES;

---------------------------------------------------------------------------------------------------
-- 8. ANALYSE PAR PRODUIT
---------------------------------------------------------------------------------------------------

SELECT
    PRODUIT,
    COUNT(*) AS NOMBRE_VENTES,
    SUM(MONTANT_TOTAL) AS TOTAL_VENTES
FROM VENTES
GROUP BY PRODUIT
ORDER BY TOTAL_VENTES DESC;

---------------------------------------------------------------------------------------------------
-- 9. ANALYSE PAR CATÉGORIE
---------------------------------------------------------------------------------------------------

SELECT
    CATEGORIE,
    SUM(MONTANT_TOTAL) AS CHIFFRE_AFFAIRES
FROM VENTES
GROUP BY CATEGORIE
ORDER BY CHIFFRE_AFFAIRES DESC;

---------------------------------------------------------------------------------------------------
-- 10. ANALYSE PAR PROVINCE
---------------------------------------------------------------------------------------------------

SELECT
    PROVINCE,
    SUM(MONTANT_TOTAL) AS TOTAL_VENTES
FROM VENTES
GROUP BY PROVINCE
ORDER BY TOTAL_VENTES DESC;

---------------------------------------------------------------------------------------------------
-- 11. ANALYSE PAR VILLE
---------------------------------------------------------------------------------------------------

SELECT
    VILLE,
    SUM(MONTANT_TOTAL) AS TOTAL_VENTES
FROM VENTES
GROUP BY VILLE
ORDER BY TOTAL_VENTES DESC;

---------------------------------------------------------------------------------------------------
-- 12. TOP 10 PRODUITS LES PLUS VENDUS
---------------------------------------------------------------------------------------------------

SELECT *
FROM
(
    SELECT
        PRODUIT,
        SUM(QUANTITE) AS QUANTITE_VENDUE
    FROM VENTES
    GROUP BY PRODUIT
    ORDER BY QUANTITE_VENDUE DESC
)
WHERE ROWNUM <= 10;

---------------------------------------------------------------------------------------------------
-- 13. ANALYSE MENSUELLE
---------------------------------------------------------------------------------------------------

SELECT
    TO_CHAR(DATE_VENTE,'YYYY-MM') AS MOIS,
    SUM(MONTANT_TOTAL) AS TOTAL_MENSUEL
FROM VENTES
GROUP BY TO_CHAR(DATE_VENTE,'YYYY-MM')
ORDER BY MOIS;

---------------------------------------------------------------------------------------------------
-- 14. ANALYSE ANNUELLE
---------------------------------------------------------------------------------------------------

SELECT
    EXTRACT(YEAR FROM DATE_VENTE) AS ANNEE,
    SUM(MONTANT_TOTAL) AS TOTAL_ANNUEL
FROM VENTES
GROUP BY EXTRACT(YEAR FROM DATE_VENTE)
ORDER BY ANNEE;

---------------------------------------------------------------------------------------------------
-- 15. CROISSANCE MENSUELLE
---------------------------------------------------------------------------------------------------

SELECT
    MOIS,
    TOTAL_MENSUEL,
    TOTAL_MENSUEL -
    LAG(TOTAL_MENSUEL)
    OVER(ORDER BY MOIS) AS VARIATION
FROM
(
    SELECT
        TO_CHAR(DATE_VENTE,'YYYY-MM') AS MOIS,
        SUM(MONTANT_TOTAL) AS TOTAL_MENSUEL
    FROM VENTES
    GROUP BY TO_CHAR(DATE_VENTE,'YYYY-MM')
);

---------------------------------------------------------------------------------------------------
-- 16. CLASSEMENT DES PRODUITS
---------------------------------------------------------------------------------------------------

SELECT
    PRODUIT,
    SUM(MONTANT_TOTAL) AS TOTAL_VENTES,
    RANK() OVER
    (
        ORDER BY SUM(MONTANT_TOTAL) DESC
    ) AS RANG
FROM VENTES
GROUP BY PRODUIT;

---------------------------------------------------------------------------------------------------
-- 17. PART DE MARCHÉ DES PRODUITS
---------------------------------------------------------------------------------------------------

SELECT
    PRODUIT,
    SUM(MONTANT_TOTAL) AS TOTAL,
    ROUND(
        100 * SUM(MONTANT_TOTAL) /
        SUM(SUM(MONTANT_TOTAL)) OVER (),
        2
    ) AS POURCENTAGE
FROM VENTES
GROUP BY PRODUIT
ORDER BY TOTAL DESC;

---------------------------------------------------------------------------------------------------
-- 18. DÉTECTION DES VALEURS EXTRÊMES
---------------------------------------------------------------------------------------------------

SELECT *
FROM VENTES
WHERE MONTANT_TOTAL >
(
    SELECT AVG(MONTANT_TOTAL)
           + (2 * STDDEV(MONTANT_TOTAL))
    FROM VENTES
);

---------------------------------------------------------------------------------------------------
-- 19. ANALYSE DES TENDANCES
---------------------------------------------------------------------------------------------------

SELECT
    DATE_VENTE,
    MONTANT_TOTAL,
    AVG(MONTANT_TOTAL)
    OVER
    (
        ORDER BY DATE_VENTE
        ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
    ) AS MOYENNE_MOBILE
FROM VENTES
ORDER BY DATE_VENTE;

---------------------------------------------------------------------------------------------------
-- 20. CLIENTS OU PRODUITS LES PLUS RENTABLES
---------------------------------------------------------------------------------------------------

SELECT
    PRODUIT,
    SUM(MONTANT_TOTAL) AS REVENU
FROM VENTES
GROUP BY PRODUIT
ORDER BY REVENU DESC;

---------------------------------------------------------------------------------------------------
-- 21. ANALYSE ABC
---------------------------------------------------------------------------------------------------

WITH ANALYSE_ABC AS
(
    SELECT
        PRODUIT,
        SUM(MONTANT_TOTAL) AS CA,
        SUM(SUM(MONTANT_TOTAL))
        OVER(ORDER BY SUM(MONTANT_TOTAL) DESC) AS CA_CUMULE,
        SUM(SUM(MONTANT_TOTAL))
        OVER() AS CA_TOTAL
    FROM VENTES
    GROUP BY PRODUIT
)
SELECT
    PRODUIT,
    CA,
    ROUND((CA_CUMULE/CA_TOTAL)*100,2) AS POURCENTAGE_CUMULE,
    CASE
        WHEN (CA_CUMULE/CA_TOTAL) <= 0.80 THEN 'A'
        WHEN (CA_CUMULE/CA_TOTAL) <= 0.95 THEN 'B'
        ELSE 'C'
    END AS CLASSE_ABC
FROM ANALYSE_ABC
ORDER BY CA DESC;

---------------------------------------------------------------------------------------------------
-- 22. CRÉATION D'UNE VUE D'ANALYSE
---------------------------------------------------------------------------------------------------

CREATE OR REPLACE VIEW VW_DASHBOARD_VENTES AS
SELECT
    TO_CHAR(DATE_VENTE,'YYYY-MM') AS MOIS,
    PROVINCE,
    VILLE,
    PRODUIT,
    SUM(QUANTITE) AS QUANTITE,
    SUM(MONTANT_TOTAL) AS CHIFFRE_AFFAIRES
FROM VENTES
GROUP BY
    TO_CHAR(DATE_VENTE,'YYYY-MM'),
    PROVINCE,
    VILLE,
    PRODUIT;

---------------------------------------------------------------------------------------------------
-- 23. CONSULTATION DE LA VUE
---------------------------------------------------------------------------------------------------

SELECT *
FROM VW_DASHBOARD_VENTES;

---------------------------------------------------------------------------------------------------
-- 24. RAPPORT EXÉCUTIF GLOBAL
---------------------------------------------------------------------------------------------------

SELECT
    COUNT(*) AS NOMBRE_VENTES,
    SUM(QUANTITE) AS QUANTITE_TOTALE,
    SUM(MONTANT_TOTAL) AS CHIFFRE_AFFAIRES,
    AVG(MONTANT_TOTAL) AS PANIER_MOYEN,
    MIN(MONTANT_TOTAL) AS VENTE_MIN,
    MAX(MONTANT_TOTAL) AS VENTE_MAX
FROM VENTES;

---------------------------------------------------------------------------------------------------
-- 25. TABLEAU DE BORD DÉCISIONNEL
---------------------------------------------------------------------------------------------------

SELECT
    PROVINCE,
    COUNT(*) AS NB_VENTES,
    SUM(MONTANT_TOTAL) AS CA_TOTAL,
    AVG(MONTANT_TOTAL) AS PANIER_MOYEN,
    ROUND(
        100 * SUM(MONTANT_TOTAL)
        /
        SUM(SUM(MONTANT_TOTAL)) OVER(),
        2
    ) AS PART_MARCHE
FROM VENTES
GROUP BY PROVINCE
ORDER BY CA_TOTAL DESC;

